const source='probes/CpiMemoProbe.sol';const content=readFileSync(source,'utf8').replace(/\r\n/g,'\n');
const input={language:'Solidity',sources:{[source]:{content},[interfacePath]:{content:header.toString('utf8')}},settings:{outputSelection:{'*':{'*':['abi','evm.bytecode.object']}}}};
