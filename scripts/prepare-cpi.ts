const contract=output.contracts[source].CpiMemoProbe;
const hadrian=getChain(200010);const memo=getPrograms('devnet').memo;
if(!hadrian||!memo)throw Error('Hadrian or Memo program absent from registry');
const programBytes=base58.decode(memo);if(programBytes.length!==32)throw Error('Invalid registry Memo program ID');
