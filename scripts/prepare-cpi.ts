const constructorArgs=encodeAbiParameters([{type:'bytes32'}],[programIdHex]);
const creationBytecode='0x'+contract.evm.bytecode.object+constructorArgs.slice(2);
const artifact={status:'STATIC_ONLY',testId:'CPI-MEMO-01',registryVersion:'v0.3.0',chainId:hadrian.chainId,programId:memo,programIdHex,compiler:version,sourceHash:'sha256:'+createHash('sha256').update(content).digest('hex'),interfaceHash:'sha256:'+createHash('sha256').update(header).digest('hex'),bytecodeHash:'sha256:'+createHash('sha256').update(Buffer.from(creationBytecode.slice(2),'hex')).digest('hex'),creationBytecode,abi:contract.abi,limitations:'Memo authority PDA signer, account meta and execution behavior require Hadrian emulation and a signed testnet transaction. No CPI success claimed.'};
